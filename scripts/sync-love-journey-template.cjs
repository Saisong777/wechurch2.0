#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..");
const outFile = path.join(repoRoot, "server", "generated", "loveJourneyTemplate.generated.ts");

const radicalFixes = new Map([
  ["⻄", "西"],
  ["⺠", "民"],
  ["⾏", "長"],
  ["⻘", "長"],
]);

const milestoneByDay = new Map([
  [6, "baptism_invitation"],
  [7, "week_1_discussion"],
  [14, "week_2_discussion"],
  [16, "communion_teaching"],
  [21, "week_3_discussion"],
  [26, "testimony_draft"],
  [28, "commissioning"],
]);

function candidateSourceDirs() {
  const dirs = [];
  if (process.env.LOVE_JOURNEY_MD_DIR) dirs.push(process.env.LOVE_JOURNEY_MD_DIR);
  dirs.push(path.join(repoRoot, "..", "..", "New project 9", "recording-md"));
  if (process.env.HOME) dirs.push(path.join(process.env.HOME, "Documents", "New project 9", "recording-md"));
  return [...new Set(dirs.map((dir) => path.resolve(dir)))];
}

function resolveSourceDir() {
  const candidates = candidateSourceDirs();
  const found = candidates.find((dir) => fs.existsSync(dir) && fs.statSync(dir).isDirectory());
  if (found) return found;
  throw new Error(`Could not find love journey recording-md directory. Tried:\n${candidates.join("\n")}`);
}

function clean(text) {
  let next = text;
  for (const [bad, good] of radicalFixes) next = next.split(bad).join(good);
  next = next.replace(/(?<=[\u4e00-\u9fff\u3001-\u30ff，。！？；：「」『』（）]) (?=[\u4e00-\u9fff「『（])/gu, "");
  return next.trim();
}

function cleanInline(text) {
  return clean(text).replaceAll("**", "").trim();
}

function stripProofingNotes(text) {
  const withRule = text.search(/\n---\s*\n\s*##\s+校稿備註/u);
  if (withRule >= 0) return text.slice(0, withRule).trim();
  const withoutRule = text.search(/\n##\s+校稿備註/u);
  if (withoutRule >= 0) return text.slice(0, withoutRule).replace(/\n---\s*$/u, "").trim();
  return text.trim();
}

function parseSections(markdown) {
  const sections = new Map();
  let current = null;
  let buffer = [];

  for (const line of markdown.split("\n")) {
    const match = line.match(/^##\s+(.*)$/u);
    if (match) {
      if (current) sections.set(current, buffer.join("\n").trim());
      current = match[1].trim();
      buffer = [];
    } else if (current) {
      buffer.push(line);
    }
  }

  if (current) sections.set(current, buffer.join("\n").trim());
  return sections;
}

function paragraphs(text) {
  return cleanInline(text)
    .split(/\n\s*\n/u)
    .map((part) => cleanInline(part))
    .filter(Boolean)
    .join("\n\n");
}

function parseDay(filePath, sourceDir) {
  const raw = fs.readFileSync(filePath, "utf8");
  const markdown = clean(stripProofingNotes(raw));
  const fileName = path.basename(filePath);
  const numberMatch = fileName.match(/^day-(\d+)/u);
  if (!numberMatch) throw new Error(`Cannot parse day number from ${fileName}`);
  const dayNumber = Number(numberMatch[1]);

  const h1 = markdown.match(/^#\s+Day\s*\d+｜(.+)$/mu);
  const title = h1 ? cleanInline(h1[1]) : fileName.replace(/\.md$/u, "");
  const weekMatch = markdown.match(/^-\s*週次：(.+)$/mu);
  const summaryMatch = markdown.match(/^-\s*摘要：(.+)$/mu);
  const typeMatch = markdown.match(/^-\s*類型：(.+)$/mu);
  const type = typeMatch ? cleanInline(typeMatch[1]) : "";
  const isGroupDay = type.includes("小組");
  const sections = parseSections(markdown);
  const reflectionKey = [...sections.keys()].find((key) => key.startsWith("默想"));
  const groupFlow = paragraphs(sections.get("小組流程") || "");

  return {
    dayNumber,
    title,
    scriptureReference: paragraphs(sections.get("主題經文") || "") || null,
    bodyMarkdown: markdown,
    actionPrompt: isGroupDay
      ? cleanInline(summaryMatch?.[1] || "小組討論、回顧與彼此禱告。")
      : paragraphs(sections.get("今日行動") || "") || null,
    reflectionPrompt: reflectionKey ? paragraphs(sections.get(reflectionKey) || "") : null,
    discussionPrompt: isGroupDay ? groupFlow : null,
    milestoneKey: milestoneByDay.get(dayNumber),
    metadata: {
      weekLabel: weekMatch ? cleanInline(weekMatch[1]) : null,
      summary: summaryMatch ? cleanInline(summaryMatch[1]) : null,
      type: type || null,
      isGroupDay,
      sourceFile: path.relative(sourceDir, filePath),
    },
  };
}

function buildGeneratedSource(days) {
  return [
    "// AUTO-GENERATED by scripts/sync-love-journey-template.cjs.",
    "// Source of truth: love-journey-app recording-md/day-*.md.",
    `export const LOVE_JOURNEY_DAYS = ${JSON.stringify(days, null, 2)} as const;`,
    "",
  ].join("\n");
}

function main() {
  const sourceDir = resolveSourceDir();
  const days = fs.readdirSync(sourceDir)
    .filter((name) => /^day-\d+.*\.md$/u.test(name))
    .sort()
    .map((name) => parseDay(path.join(sourceDir, name), sourceDir))
    .sort((a, b) => a.dayNumber - b.dayNumber);

  const problems = [];
  if (days.length !== 28) problems.push(`expected 28 days, got ${days.length}`);
  for (let index = 0; index < days.length; index += 1) {
    const expectedDay = index + 1;
    const day = days[index];
    if (day.dayNumber !== expectedDay) problems.push(`expected day ${expectedDay}, got day ${day.dayNumber}`);
    if (!day.title) problems.push(`day ${day.dayNumber}: missing title`);
    if (!day.bodyMarkdown) problems.push(`day ${day.dayNumber}: missing bodyMarkdown`);
    if (day.metadata.isGroupDay && !day.discussionPrompt) problems.push(`day ${day.dayNumber}: missing discussionPrompt`);
    if (!day.metadata.isGroupDay && !day.actionPrompt) problems.push(`day ${day.dayNumber}: missing actionPrompt`);
  }

  if (problems.length) {
    for (const problem of problems) console.error(`ERROR: ${problem}`);
    process.exit(1);
  }

  const nextSource = buildGeneratedSource(days);
  const checkOnly = process.argv.includes("--check");
  const currentSource = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null;
  if (checkOnly) {
    if (currentSource !== nextSource) {
      console.error(`${path.relative(repoRoot, outFile)} is stale. Run npm run love-journey:sync.`);
      process.exit(1);
    }
    console.log(`OK: ${path.relative(repoRoot, outFile)} matches ${path.relative(repoRoot, sourceDir)}`);
    return;
  }

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, nextSource, "utf8");
  console.log(`OK: wrote ${path.relative(repoRoot, outFile)} from ${path.relative(repoRoot, sourceDir)} (${days.length} days)`);
}

main();
